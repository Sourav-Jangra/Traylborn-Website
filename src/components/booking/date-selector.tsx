"use client";

import { useMemo, useState } from "react";
import { ChevronLeft, ChevronRight, Info } from "lucide-react";
import type { Departure } from "@/lib/utils/departures";
import { addDays, formatDateLong, parseISODate, toISODate } from "@/lib/utils/format";
import { cn } from "@/lib/utils";

interface DateSelectorProps {
  departures: Departure[];
  value: string | null;
  onChange: (date: string) => void;
  durationDays: number;
  ruleLabel?: string;
  compact?: boolean;
}

const WEEKDAYS = ["Mo", "Tu", "We", "Th", "Fr", "Sa", "Su"];

function monthKey(iso: string) {
  return iso.slice(0, 7);
}

/**
 * Month calendar that only enables dates generated by the package's departure
 * rule (daily / weekly / fixed). Everything else is shown but not selectable.
 */
export function DateSelector({ departures, value, onChange, durationDays, ruleLabel, compact }: DateSelectorProps) {
  const byDate = useMemo(() => new Map(departures.map((d) => [d.date, d])), [departures]);
  const months = useMemo(() => Array.from(new Set(departures.map((d) => monthKey(d.date)))), [departures]);
  const [monthIndex, setMonthIndex] = useState(() => {
    const i = value ? months.indexOf(monthKey(value)) : 0;
    return Math.max(0, i);
  });
  const [syncedValue, setSyncedValue] = useState(value);
  if (value !== syncedValue) {
    setSyncedValue(value);
    const i = value ? months.indexOf(monthKey(value)) : -1;
    if (i >= 0) setMonthIndex(i);
  }

  if (months.length === 0) {
    return <p className="rounded-2xl bg-sand-100 p-5 text-sm text-muted-foreground">New departures will be announced soon.</p>;
  }

  const current = months[Math.min(monthIndex, months.length - 1)];
  const first = parseISODate(`${current}-01`);
  const daysInMonth = new Date(first.getFullYear(), first.getMonth() + 1, 0).getDate();
  const leading = (first.getDay() + 6) % 7;
  const cells: (string | null)[] = [
    ...Array.from({ length: leading }, () => null),
    ...Array.from({ length: daysInMonth }, (_, i) => toISODate(new Date(first.getFullYear(), first.getMonth(), i + 1))),
  ];
  const selected = value ? byDate.get(value) : undefined;
  const datesThisMonth = departures.filter((d) => monthKey(d.date) === current).length;

  return (
    <div>
      {ruleLabel && (
        <p className="mb-4 flex items-center gap-2 rounded-xl bg-pine-50 px-3.5 py-2.5 text-sm text-pine-800">
          <Info className="size-4 shrink-0" aria-hidden="true" />
          {ruleLabel}
        </p>
      )}

      <div className="flex items-center justify-between">
        <button
          type="button"
          onClick={() => setMonthIndex((i) => Math.max(0, i - 1))}
          disabled={monthIndex === 0}
          aria-label="Previous month"
          className="grid size-10 place-items-center rounded-full border border-border bg-white transition-colors hover:border-pine-400 disabled:opacity-30"
        >
          <ChevronLeft className="size-4" />
        </button>
        <div className="text-center" aria-live="polite">
          <p className="font-display text-lg font-semibold">
            {first.toLocaleDateString("en-IN", { month: "long", year: "numeric" })}
          </p>
          <p className="text-xs text-muted-foreground">{datesThisMonth} departure {datesThisMonth === 1 ? "date" : "dates"}</p>
        </div>
        <button
          type="button"
          onClick={() => setMonthIndex((i) => Math.min(months.length - 1, i + 1))}
          disabled={monthIndex >= months.length - 1}
          aria-label="Next month"
          className="grid size-10 place-items-center rounded-full border border-border bg-white transition-colors hover:border-pine-400 disabled:opacity-30"
        >
          <ChevronRight className="size-4" />
        </button>
      </div>

      <div role="group" aria-label="Departure dates" className="mt-4">
        <div aria-hidden="true" className="grid grid-cols-7 text-center text-[0.7rem] font-semibold tracking-wider text-muted-foreground uppercase">
          {WEEKDAYS.map((d) => (
            <span key={d} className="py-1.5">{d}</span>
          ))}
        </div>
        <div className="mt-1 grid grid-cols-7 gap-1">
          {cells.map((iso, i) => {
            if (!iso) return <span key={`blank-${i}`} />;
            const bookable = byDate.has(iso);
            const isSelected = value === iso;
            const day = Number(iso.slice(8));
            return (
              <span key={iso}>
                <button
                  type="button"
                  disabled={!bookable}
                  onClick={() => bookable && onChange(iso)}
                  aria-pressed={isSelected}
                  aria-label={`${formatDateLong(iso)}${bookable ? "" : ", not available"}`}
                  className={cn(
                    "relative flex w-full flex-col items-center justify-center rounded-xl font-medium transition-all",
                    compact ? "h-11 text-sm" : "h-12 text-sm sm:h-14 sm:text-base",
                    !bookable && "cursor-not-allowed text-ink/25",
                    bookable && !isSelected && "bg-white text-ink ring-1 ring-border hover:ring-2 hover:ring-pine-600",
                    isSelected && "bg-pine-800 text-white shadow-lg shadow-pine-800/25",
                  )}
                >
                  {day}
                  {bookable && (
                    <span
                      aria-hidden="true"
                      className={cn(
                        "absolute bottom-1.5 size-1 rounded-full",
                        isSelected ? "bg-ember-400" : "bg-moss-500",
                      )}
                    />
                  )}
                </button>
              </span>
            );
          })}
        </div>
      </div>

      <div className="mt-4 flex flex-wrap gap-x-4 gap-y-1.5 text-xs text-muted-foreground">
        <span className="flex items-center gap-1.5"><span className="size-2 rounded-full bg-moss-500" /> Departure date</span>
      </div>

      {selected && (
        <div className="mt-4 rounded-2xl border border-pine-200 bg-pine-50 p-4 text-sm">
          <p className="font-semibold text-pine-800">{formatDateLong(selected.date)}</p>
          <p className="mt-0.5 text-pine-700">Returns {formatDateLong(addDays(selected.date, durationDays - 1))}</p>
        </div>
      )}
    </div>
  );
}
