-- Baseline: the packages table as it existed before migrations were introduced.
-- Databases created before the migration runner already have this table; the
-- runner adopts it as applied instead of running this file (see scripts/migrate.mjs).
-- Nested package content is stored as JSON so it maps 1:1 onto the TravelPackage type.

CREATE TABLE packages (
  id               INT UNSIGNED NOT NULL AUTO_INCREMENT,
  slug             VARCHAR(160) NOT NULL,
  title            VARCHAR(200) NOT NULL,
  tagline          VARCHAR(300) NOT NULL DEFAULT '',
  category         ENUM('treks', 'road-trips', 'retreats') NOT NULL,
  region           VARCHAR(120) NOT NULL DEFAULT '',
  state            VARCHAR(120) NOT NULL DEFAULT '',
  destination      VARCHAR(160) NOT NULL DEFAULT '',
  starting_point   VARCHAR(120) NOT NULL DEFAULT '',
  ending_point     VARCHAR(120) NOT NULL DEFAULT '',
  duration_days    SMALLINT UNSIGNED NOT NULL,
  nights           SMALLINT UNSIGNED NOT NULL,
  price            INT UNSIGNED NOT NULL COMMENT 'INR per person',
  original_price   INT UNSIGNED NULL COMMENT 'INR; shown struck-through when greater than price',
  difficulty       ENUM('Easy', 'Moderate', 'Challenging') NOT NULL,
  max_altitude     VARCHAR(60) NULL,
  distance         VARCHAR(60) NULL,
  group_size       VARCHAR(60) NOT NULL DEFAULT '',
  age_limit        VARCHAR(60) NOT NULL DEFAULT '',
  description      TEXT NOT NULL,
  video            VARCHAR(500) NULL,
  departure_label  VARCHAR(120) NOT NULL DEFAULT '',
  featured         TINYINT(1) NOT NULL DEFAULT 0,
  status           ENUM('published', 'draft', 'archived') NOT NULL DEFAULT 'draft',
  badge            VARCHAR(40) NULL,
  images           JSON NOT NULL,
  highlights       JSON NOT NULL,
  itinerary        JSON NOT NULL,
  inclusions       JSON NOT NULL,
  exclusions       JSON NOT NULL,
  things_to_carry  JSON NULL,
  faqs             JSON NOT NULL,
  best_season      JSON NOT NULL,
  tags             JSON NOT NULL,
  departure_rule   JSON NOT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY packages_slug_unique (slug),
  KEY packages_status_category (status, category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
